"""Plot fallback methods on the campaign's shared eligible physical panels.

Usage: python examples/plot_weather_campaign_methods.py CAMPAIGN/analysis
Incomplete analyses require --provisional. Meteorology and solar are separate
figures; no weather engines or additional climate experiments are invoked.
These conditional scenario quantiles are descriptive, not confidence limits.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import sys
from datetime import UTC, datetime
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from matplotlib.lines import Line2D

IDENTITY = [
    "site_id",
    "year",
    "building_id",
    "scope",
    "sampling",
    "gap_hours",
    "physical_signature",
]
PHYSICAL = [c for c in IDENTITY if c != "building_id"]
DURATIONS = (3, 12, 48, 168)
SAMPLINGS = (
    ("random_seasonal", "Seasonal random outages"),
    ("weather_extremes", "Weather event outages"),
)
METHODS = {
    "temporal": ("Temporal recovery", "#009E73", "s"),
    "donor_assessed": ("Assessed donor", "#CC79A7", "D"),
    "era5": ("ERA5", "#56B4E9", "v"),
    "automatic": ("Current hierarchy", "#0072B2", "o"),
    "automatic_legacy": ("Previous hierarchy", "#D55E00", "P"),
}
METRICS = (
    ("absolute_annual_heating_error_kwh_m2", "Annual heating error", "kWh/m²"),
    ("absolute_annual_cooling_error_kwh_m2", "Annual cooling error", "kWh/m²"),
    ("absolute_peak_heating_error_w_m2", "Heating peak error", "W/m²"),
    ("absolute_peak_cooling_error_w_m2", "Cooling peak error", "W/m²"),
)
SUMMARY_COLUMNS = [
    "scope",
    "sampling",
    "gap_hours",
    "method",
    "metric",
    "unit",
    "physical_panels",
    "site_years",
    "building_responses",
    "median",
    "empirical_p95",
]


def sha(data):
    """Fingerprint exact captured and generated bytes for publication provenance."""
    return hashlib.sha256(data).hexdigest()


def methods_for(matrix, scope, hours):
    """Use scheduled methods and exclude unsupported temporal gaps above forty-eight hours."""
    key = "meteorology_methods" if scope == "meteorology" else "solar_methods"
    return [m for m in matrix[key] if m != "temporal" or hours <= 48]


def validate_cohort(rows, matrix):
    """Require identical physical panels and complete scheduled methods across building profiles."""
    expected_columns = (
        IDENTITY + ["method", "floor_area_m2"] + [m for m, _, _ in METRICS]
    )
    buildings = set(matrix["buildings"])
    if not buildings or any(
        not matrix[key]
        or len(set(matrix[key])) != len(matrix[key])
        or set(matrix[key]) - set(METHODS)
        for key in ("meteorology_methods", "solar_methods")
    ):
        raise ValueError(
            "Campaign buildings and scheduled plotting methods must be defined"
        )
    if rows.empty:
        return pd.DataFrame(columns=expected_columns)
    if set(expected_columns) - set(rows):
        raise ValueError("Common-method comparison schema is incomplete")
    result = rows.copy()
    if result[IDENTITY + ["method"]].isna().any().any():
        raise ValueError("Common-cohort identities cannot contain missing values")
    if (
        not result.scope.isin(("meteorology", "solar")).all()
        or not result.sampling.isin([s for s, _ in SAMPLINGS]).all()
        or not result.gap_hours.isin(DURATIONS).all()
        or not result.building_id.isin(buildings).all()
    ):
        raise ValueError("Common-method rows contain unsupported campaign strata")
    if result.duplicated(IDENTITY + ["method"]).any():
        raise ValueError(
            "Duplicate physical comparisons would overweight method errors"
        )
    for column in ["floor_area_m2"] + [m for m, _, _ in METRICS]:
        values = pd.to_numeric(result[column], errors="coerce")
        if not np.isfinite(values).all() or values.lt(0).any():
            raise ValueError(
                "Method errors and floor areas must be finite and nonnegative"
            )
        if column == "floor_area_m2" and values.eq(0).any():
            raise ValueError("Building floor areas must be strictly positive")
        result[column] = values
    for _, group in result.groupby(IDENTITY, dropna=False):
        row = group.iloc[0]
        required = set(methods_for(matrix, row.scope, row.gap_hours))
        if set(group.method) != required:
            raise ValueError(
                "A common physical comparison is missing scheduled methods"
            )
        if group.floor_area_m2.nunique() != 1:
            raise ValueError("Paired methods must share the same building floor area")
    for _, group in result.groupby(PHYSICAL, dropna=False):
        if set(group.building_id) != buildings:
            raise ValueError(
                "Common weather panels must contain every campaign building"
            )
    return result


def summarize(rows, matrix):
    """Describe each shared-method stratum without multiplying physical weather-panel counts."""
    records = []
    if rows.empty:
        return pd.DataFrame(columns=SUMMARY_COLUMNS)
    for (scope, sampling, hours, method), group in rows.groupby(
        ["scope", "sampling", "gap_hours", "method"], sort=True
    ):
        if method not in methods_for(matrix, scope, hours):
            raise ValueError(
                "Unsupported temporal recovery cannot enter the method summary"
            )
        for metric, _, unit in METRICS:
            records.append(
                {
                    "scope": scope,
                    "sampling": sampling,
                    "gap_hours": int(hours),
                    "method": method,
                    "metric": metric,
                    "unit": unit,
                    "physical_panels": len(group[PHYSICAL].drop_duplicates()),
                    "site_years": len(group[["site_id", "year"]].drop_duplicates()),
                    "building_responses": len(group),
                    "median": float(group[metric].median()),
                    "empirical_p95": float(group[metric].quantile(0.95)),
                }
            )
    return pd.DataFrame(records, columns=SUMMARY_COLUMNS)


def render_scope(summary, scope, matrix, provisional):
    """Draw conditional absolute-load errors for one shared meteorological or solar cohort."""
    fig, axes = plt.subplots(4, 2, figsize=(14, 14.5))
    methods = methods_for(matrix, scope, 3)
    for row, (metric, label, unit) in enumerate(METRICS):
        for column, (sampling, selection) in enumerate(SAMPLINGS):
            ax = axes[row, column]
            group = summary.loc[
                summary.scope.eq(scope)
                & summary.sampling.eq(sampling)
                & summary.metric.eq(metric)
            ]
            ticks = []
            for hours in DURATIONS:
                selected = group.loc[group.gap_hours.eq(hours)]
                counts = selected.iloc[0] if not selected.empty else None
                panels, years, responses = (
                    (
                        int(counts.physical_panels),
                        int(counts.site_years),
                        int(counts.building_responses),
                    )
                    if counts is not None
                    else (0, 0, 0)
                )
                ticks.append(f"{hours}\nP{panels}/Y{years}\nB{responses}")
            offsets = np.linspace(-0.11, 0.11, len(methods))
            for offset, method in zip(offsets, methods):
                _, color, marker = METHODS[method]
                values = (
                    group.loc[group.method.eq(method)]
                    .set_index("gap_hours")
                    .reindex(DURATIONS)
                )
                x = np.arange(4) + offset
                ax.plot(
                    x,
                    values["median"],
                    color=color,
                    marker=marker,
                    linewidth=1.6,
                    markersize=4,
                )
                ax.plot(
                    x,
                    values["empirical_p95"],
                    color=color,
                    marker=marker,
                    linestyle="--",
                    linewidth=1.2,
                    markersize=4,
                    alpha=0.75,
                )
            ax.set_xticks(range(4), ticks)
            ax.set_xlim(-0.4, 3.4)
            ax.set_ylim(bottom=0)
            ax.set_xlabel("Hours per block", fontsize=9)
            ax.set_ylabel(f"{label}\n({unit}, absolute)", fontsize=10)
            ax.set_title(selection, fontsize=11)
            ax.tick_params(labelsize=9)
            ax.grid(axis="y", color="#dddddd", linewidth=0.6)
            ax.spines[["top", "right"]].set_visible(False)
            if group.empty:
                ax.text(
                    0.5,
                    0.5,
                    "No common eligible panels",
                    transform=ax.transAxes,
                    ha="center",
                    color="#666666",
                )
    fig.suptitle(
        ("Meteorological" if scope == "meteorology" else "Solar")
        + " fallback methods on shared eligible panels"
        + (" — PROVISIONAL" if provisional else ""),
        y=0.985,
        fontsize=16,
        fontweight="bold",
    )
    handles = [
        Line2D([0], [0], color=METHODS[m][1], marker=METHODS[m][2], label=METHODS[m][0])
        for m in methods
    ]
    fig.legend(
        handles=handles,
        loc="upper center",
        bbox_to_anchor=(0.5, 0.95),
        ncol=len(methods),
        frameon=False,
        fontsize=10,
    )
    styles = [
        Line2D([0], [0], color="#444444", linestyle=style, label=label)
        for style, label in (("-", "Median"), ("--", "95th empirical percentile"))
    ]
    fig.legend(
        handles=styles,
        loc="upper center",
        bbox_to_anchor=(0.5, 0.92),
        ncol=2,
        frameon=False,
        fontsize=10,
    )
    caption = "P: shared physical weather panels; Y: site-years; B: building responses per method. These counts repeat for each load metric; six profiles share each climate.\n"
    caption += "Seasonal random: 4 blocks/file (4×hours); weather event: 1 block/file. Comparisons are within each sampling/duration stratum; temporal is unsupported above 48h.\n"
    caption += (
        "Meteorological panels require assessed-donor availability and acceptance. This selected cohort cannot establish an all-location method ranking.\n"
        if scope == "meteorology"
        else "Solar uses hybrid measured-GHI/STRÅNG references and estimated components; these proxy comparisons are not validation against independent measured DNI/DHI.\n"
    )
    caption += "Building outcomes require warning-free runs and reference baselines. Different durations can have different eligible panel sets.\n"
    caption += "Medians and empirical tails describe these selected responses, not confidence intervals or national uncertainty."
    fig.text(0.5, 0.025, caption, ha="center", va="bottom", fontsize=9)
    fig.subplots_adjust(
        top=0.86, bottom=0.135, left=0.08, right=0.98, hspace=0.65, wspace=0.22
    )
    return fig


def plot(root, *, provisional=False):
    """Verify completed analysis and publish matched-cohort figures for both weather scopes."""
    root = Path(root)
    manifest_bytes = (root / "manifest.json").read_bytes()
    manifest = json.loads(manifest_bytes)
    incomplete = manifest["status"] != "complete" or bool(manifest.get("incomplete"))
    if incomplete and not provisional:
        raise ValueError("Incomplete analysis requires explicit --provisional")
    partial = provisional or incomplete
    name = "common-method-comparisons.csv"
    data = (root / name).read_bytes()
    if sha(data) != manifest["outputs"].get(name):
        raise ValueError("Common-method table differs from its analysis receipt")
    try:
        rows = pd.read_csv(io.BytesIO(data))
    except pd.errors.EmptyDataError:
        rows = pd.DataFrame()
    if len(rows) != manifest["common_method_comparisons"]:
        raise ValueError("Common-method row count differs from its analysis manifest")
    matrix_bytes = (Path(manifest["campaign_root"]) / "matrix.json").read_bytes()
    if sha(matrix_bytes) != manifest["matrix_sha256"]:
        raise ValueError("Campaign matrix differs from its analysis fingerprint")
    matrix = json.loads(matrix_bytes)
    rows = validate_cohort(rows, matrix)
    summary = summarize(rows, matrix)
    folder = root / "method-figures"
    folder.mkdir(parents=True, exist_ok=True)
    plt.rcParams.update(
        {"font.family": "DejaVu Sans", "svg.fonttype": "none", "axes.axisbelow": True}
    )
    outputs = {}
    for scope in ("meteorology", "solar"):
        fig = render_scope(summary, scope, matrix, partial)
        for extension in ("png", "svg"):
            path = folder / f"common-method-{scope}-errors.{extension}"
            fig.savefig(path, dpi=200, facecolor="white")
            outputs[path.name] = sha(path.read_bytes())
        plt.close(fig)
    table_path = folder / "figure-data.csv"
    summary.to_csv(table_path, index=False)
    outputs[table_path.name] = sha(table_path.read_bytes())
    receipt = {
        "status": "provisional" if partial else "complete",
        "created_utc": datetime.now(UTC).isoformat(),
        "plotter_sha256": sha(Path(__file__).read_bytes()),
        "analysis_manifest_sha256": sha(manifest_bytes),
        "common_method_table_sha256": sha(data),
        "matrix_sha256": sha(matrix_bytes),
        "python": sys.version,
        "matplotlib": matplotlib.__version__,
        "numpy": np.__version__,
        "pandas": pd.__version__,
        "building_responses_including_methods": len(rows),
        "shared_physical_panels": {
            scope: len(rows.loc[rows.scope.eq(scope), PHYSICAL].drop_duplicates())
            for scope in ("meteorology", "solar")
        },
        "outputs": outputs,
        "interpretation": "Scheduled methods share identical eligible physical weather panels and all campaign profiles within each sampling/duration stratum. Temporal is omitted above 48h. Meteorological common panels are conditional on assessed-donor availability and acceptance; no overall donor ranking is inferred. Solar components are proxy references. Zero/tiny loads remain in absolute errors. Counts distinguish weather panels, site-years, and building responses; empirical tails are not population confidence intervals.",
    }
    (folder / "manifest.json").write_text(
        json.dumps(receipt, indent=2, allow_nan=False) + "\n"
    )
    return receipt


def main():
    """Render verified final common-method evidence or explicitly marked provisional figures."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("analysis_root", type=Path)
    parser.add_argument("--provisional", action="store_true")
    args = parser.parse_args()
    receipt = plot(args.analysis_root, provisional=args.provisional)
    print(
        json.dumps(
            {
                k: receipt[k]
                for k in (
                    "status",
                    "shared_physical_panels",
                    "building_responses_including_methods",
                )
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()

"""Plot paired campaign evidence from the independent postanalysis tables.

Usage: python examples/plot_weather_imputation_campaign.py CAMPAIGN/analysis
Incomplete analyses require --provisional and every resulting figure is marked.
The figures describe selected synthetic-building/outage scenarios. Percentile
tails and site-year spreads are empirical descriptions, not confidence limits.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import sys
from datetime import UTC, datetime
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from matplotlib.lines import Line2D

KEYS = [
    "site_id",
    "year",
    "building_id",
    "scope",
    "sampling",
    "gap_hours",
    "physical_signature",
]
DURATIONS = (3, 12, 48, 168)
SAMPLINGS = (
    ("random_seasonal", "Seasonal random outages"),
    ("weather_extremes", "Weather event outages"),
)
SIDES = (
    ("new", "Current hierarchy", "#0072B2"),
    ("old", "Previous hierarchy", "#D55E00"),
)
BUILDINGS = {
    "detached_old_light": "Detached\nold/light",
    "detached_new_heavy": "Detached\nnew/heavy",
    "multifamily_old": "Multifamily\nold",
    "multifamily_new": "Multifamily\nnew",
    "office_glazed": "Office\nglazed",
    "school_daytime": "School\ndaytime",
}


def sha(data):
    """Fingerprint the exact bytes used or generated by this plotter."""
    return hashlib.sha256(data).hexdigest()


def verified_table(root, manifest, name):
    """Read one table only when its captured bytes match the analysis receipt."""
    data = (root / name).read_bytes()
    if sha(data) != manifest["outputs"].get(name):
        raise ValueError(f"Analysis table differs from its manifest: {name}")
    try:
        return pd.read_csv(io.BytesIO(data))
    except pd.errors.EmptyDataError:
        return pd.DataFrame()


def plot_inputs(root, manifest):
    """Join percentage and timing fields onto the already paired physical cohort."""
    pairs = verified_table(root, manifest, "hierarchy-pairs.csv")
    if pairs.empty:
        raise ValueError("No matched automatic hierarchy comparisons to plot")
    if len(pairs) != manifest["hierarchy_pairs"]:
        raise ValueError("Plot cohort differs from the declared hierarchy pair count")
    rows = verified_table(root, manifest, "deduplicated-comparisons.csv")
    pairs = pairs.loc[pairs.scope.eq("meteorology")].copy()
    if pairs.empty or pairs.duplicated(KEYS).any():
        raise ValueError("A unique matched meteorological cohort is required")
    met_pairs = len(pairs)
    extra = [
        f"delta_{quantity}_{mode}_pct"
        for quantity in ("annual", "peak")
        for mode in ("heating", "cooling")
    ]
    extra += [f"nearest_{mode}_peak_shift_h" for mode in ("heating", "cooling")]
    extra += [f"baseline_annual_{mode}_kwh_m2" for mode in ("heating", "cooling")]
    for side, method in (("new", "automatic"), ("old", "automatic_legacy")):
        selected = rows.loc[rows.method.eq(method), KEYS + extra]
        pairs = pairs.merge(
            selected.rename(columns={c: c + "_" + side for c in extra}),
            on=KEYS,
            validate="one_to_one",
        )
    if len(pairs) != met_pairs:
        raise ValueError(
            "Percentage fields do not cover the meteorological pair cohort"
        )
    return pairs


def finish(fig, title, caption, provisional):
    """Apply readable typography and visibly label any incomplete campaign evidence."""
    if not provisional:
        caption += "\nBuilding outcomes use only warning-free runs and warning-free reference baselines."
    fig.suptitle(
        title + (" — PROVISIONAL" if provisional else ""),
        y=0.98,
        fontsize=15,
        fontweight="bold",
    )
    fig.text(0.5, 0.025, caption, ha="center", va="bottom", fontsize=9, wrap=True)
    for ax in fig.axes:
        ax.grid(axis="y", color="#dddddd", linewidth=0.6)
        ax.spines[["top", "right"]].set_visible(False)
        ax.tick_params(labelsize=9)


def save(fig, folder, stem, outputs):
    """Save both sharing and vector formats with exact output fingerprints."""
    for extension in ("png", "svg"):
        path = folder / f"{stem}.{extension}"
        fig.savefig(path, dpi=200, facecolor="white")
        outputs[path.name] = sha(path.read_bytes())
    plt.close(fig)


def error_figure(pairs, quantity, provisional):
    """Show medians and empirical tails for each paired duration and sampling stratum."""
    fig, axes = plt.subplots(2, 4, figsize=(16, 8.5))
    units = "kWh/m²" if quantity == "annual" else "W/m²"
    stats = []
    for mode_index, mode in enumerate(("heating", "cooling")):
        for sampling_index, (sampling, label) in enumerate(SAMPLINGS):
            for percent in (False, True):
                ax = axes[mode_index, 2 * sampling_index + int(percent)]
                group = pairs.loc[pairs.sampling.eq(sampling)]
                medians, tails = (
                    {s: [] for s, _, _ in SIDES},
                    {s: [] for s, _, _ in SIDES},
                )
                ticks = []
                for hours in DURATIONS:
                    selected = group.loc[group.gap_hours.eq(hours)].copy()
                    if percent:
                        columns = [
                            f"delta_{quantity}_{mode}_pct_{s}" for s, _, _ in SIDES
                        ]
                        if quantity == "peak":
                            selected = selected.loc[
                                selected[f"baseline_peak_{mode}_w_m2"].gt(1e-6)
                            ]
                    else:
                        suffix = "kwh_m2" if quantity == "annual" else "w_m2"
                        columns = [
                            f"absolute_{quantity}_{mode}_error_{suffix}_{s}"
                            for s, _, _ in SIDES
                        ]
                    values = (
                        selected[columns]
                        .apply(pd.to_numeric, errors="coerce")
                        .replace([np.inf, -np.inf], np.nan)
                    )
                    selected = selected.loc[values.notna().all(axis=1)]
                    values = values.loc[selected.index].abs()
                    site_years = len(selected[["site_id", "year"]].drop_duplicates())
                    ticks.append(f"{hours}\n{len(selected)}/{site_years}")
                    for side, column in zip((s for s, _, _ in SIDES), columns):
                        median, tail = (
                            values[column].median(),
                            values[column].quantile(0.95),
                        )
                        medians[side].append(median)
                        tails[side].append(tail)
                        stats.append(
                            {
                                "figure": quantity,
                                "mode": mode,
                                "sampling": sampling,
                                "gap_hours": hours,
                                "unit": "%" if percent else units,
                                "hierarchy": side,
                                "paired_responses": len(selected),
                                "site_years": site_years,
                                "median": float(median) if pd.notna(median) else None,
                                "empirical_p95": float(tail)
                                if pd.notna(tail)
                                else None,
                            }
                        )
                    if percent and quantity == "annual" and mode == "cooling":
                        tiny = selected.baseline_annual_cooling_kwh_m2_new.lt(1).sum()
                        for record in stats[-2:]:
                            record["tiny_reference_cooling_responses"] = int(tiny)
                for offset, (side, _, color) in zip((-0.055, 0.055), SIDES):
                    x = np.arange(4) + offset
                    ax.plot(
                        x,
                        medians[side],
                        color=color,
                        marker="o",
                        linewidth=1.7,
                        markersize=4,
                    )
                    ax.plot(
                        x,
                        tails[side],
                        color=color,
                        marker="^",
                        linestyle="--",
                        linewidth=1.3,
                        markersize=4,
                    )
                ax.set_xticks(range(4), ticks)
                ax.set_xlim(-0.3, 3.3)
                ax.set_xlabel(
                    "Hours per block\npaired responses/location-years", fontsize=9
                )
                ax.set_ylabel(
                    f"Absolute {mode} error ({'%' if percent else units})", fontsize=10
                )
                ax.set_title(
                    label + (" · percentage" if percent else " · absolute"), fontsize=10
                )
                ax.set_ylim(bottom=0)
    handles = [
        Line2D([0], [0], color=color, marker="o", label=label)
        for _, label, color in SIDES
    ]
    handles += [
        Line2D([0], [0], color="#444444", marker="o", label="Median"),
        Line2D(
            [0],
            [0],
            color="#444444",
            marker="^",
            linestyle="--",
            label="95th empirical percentile",
        ),
    ]
    fig.legend(
        handles=handles,
        loc="upper center",
        bbox_to_anchor=(0.5, 0.935),
        ncol=4,
        frameon=False,
    )
    caption = "Identical physical masks, six illustrative building profiles; N counts paired responses, not independent climates. Percentile tails are descriptive, not confidence limits.\n"
    caption += (
        "Positive but tiny cooling baselines remain in percentage panels: use the adjacent absolute errors to assess magnitude."
        if quantity == "annual"
        else "Percentage panels exclude zero/numerical reference peaks ≤10⁻⁶ W/m²; absolute panels retain their errors."
    )
    caption += "\nSeasonal random: 4 blocks/file (4×hours); weather event: 1 block/file. Method comparisons are within each sampling stratum."
    finish(fig, f"Paired {quantity} sensible-load errors", caption, provisional)
    fig.subplots_adjust(
        top=0.84, bottom=0.21, left=0.07, right=0.99, hspace=0.5, wspace=0.4
    )
    return fig, stats


def profile_figure(pairs, provisional):
    """Describe building-conditional changes across equally weighted site-year means."""
    fig, axes = plt.subplots(2, 2, figsize=(13, 9))
    stats = []
    present = [b for b in BUILDINGS if b in set(pairs.building_id)]
    for row, mode in enumerate(("heating", "cooling")):
        for column, (sampling, label) in enumerate(SAMPLINGS):
            ax = axes[row, column]
            ax.axhline(0, color="#777777", linewidth=1)
            counts = {b: {} for b in present}
            point_count = 0
            for hours, color, marker, offset in (
                (12, "#0072B2", "o", -0.10),
                (48, "#009E73", "D", 0.10),
            ):
                for i, building in enumerate(present):
                    selected = pairs.loc[
                        pairs.sampling.eq(sampling)
                        & pairs.gap_hours.eq(hours)
                        & pairs.building_id.eq(building)
                    ]
                    metric = f"absolute_annual_{mode}_error_kwh_m2_change"
                    means = (
                        selected.groupby(["site_id", "year"])[metric].mean().dropna()
                    )
                    counts[building][hours] = (len(selected), len(means))
                    if means.empty:
                        continue
                    point_count += 1
                    median, low, high = (
                        means.median(),
                        means.quantile(0.05),
                        means.quantile(0.95),
                    )
                    ax.errorbar(
                        i + offset,
                        median,
                        yerr=[[median - low], [high - median]],
                        fmt=marker,
                        color=color,
                        capsize=3,
                        markersize=5,
                    )
                    stats.append(
                        {
                            "figure": "profiles",
                            "mode": mode,
                            "sampling": sampling,
                            "gap_hours": hours,
                            "building_id": building,
                            "paired_responses": len(selected),
                            "site_years": len(means),
                            "site_year_mean_median_change_kwh_m2": float(median),
                            "empirical_site_year_p05": float(low),
                            "empirical_site_year_p95": float(high),
                        }
                    )
            labels = [
                BUILDINGS[b]
                + f"\nN {counts[b][12][0]}/{counts[b][48][0]}"
                + f"\nY {counts[b][12][1]}/{counts[b][48][1]}"
                for b in present
            ]
            ax.set_xticks(range(len(present)), labels)
            ax.set_xlim(-0.5, len(present) - 0.5)
            if not point_count:
                ax.text(
                    0.5,
                    0.5,
                    "No paired 12/48h results",
                    transform=ax.transAxes,
                    ha="center",
                    color="#666666",
                    fontsize=10,
                )
            ax.set_title(label, fontsize=11)
            ax.set_ylabel(
                f"New − previous absolute {mode} error\n(kWh/m²; negative favors current)",
                fontsize=10,
            )
    fig.legend(
        handles=[
            Line2D([0], [0], color=c, marker=m, label=f"{h}h blocks")
            for h, c, m in ((12, "#0072B2", "o"), (48, "#009E73", "D"))
        ],
        loc="upper center",
        bbox_to_anchor=(0.5, 0.94),
        ncol=2,
        frameon=False,
    )
    caption = "Points: median of site-year means; whiskers: empirical 5th–95th percentiles, with equal site-year weights.\nN: paired responses; Y: eligible site-years, both in 12h/48h order. Spreads describe these selected synthetic profiles and climate records; they are not confidence intervals."
    caption += "\nSeasonal random: 4 blocks/file (4×hours); weather event: 1 block/file. Method comparisons are within each sampling stratum."
    finish(fig, "Paired hierarchy changes by building profile", caption, provisional)
    fig.subplots_adjust(
        top=0.84, bottom=0.18, left=0.09, right=0.97, hspace=0.65, wspace=0.32
    )
    return fig, stats


def peak_timing_figure(pairs, provisional):
    """Restrict exact peak-hour-set preservation to positive exposed reference peaks."""
    fig, axes = plt.subplots(2, 2, figsize=(12, 8))
    stats = []
    for row, mode in enumerate(("heating", "cooling")):
        for column, (sampling, label) in enumerate(SAMPLINGS):
            ax = axes[row, column]
            groups = pairs.loc[pairs.sampling.eq(sampling)]
            ticks, bars = [], {s: [] for s, _, _ in SIDES}
            for hours in DURATIONS:
                selected = groups.loc[groups.gap_hours.eq(hours)]
                positive = selected[f"baseline_peak_{mode}_w_m2"].gt(1e-6)
                exposed = (
                    selected[f"baseline_{mode}_peak_hidden_new"].eq(True) & positive
                )
                unexposed = int((positive & ~exposed).sum())
                numerical = int((~positive).sum())
                site_years = len(
                    selected.loc[exposed, ["site_id", "year"]].drop_duplicates()
                )
                ticks.append(
                    f"{hours}h\nE{int(exposed.sum())}/U{unexposed}\nY{site_years}"
                )
                for side, _, _ in SIDES:
                    same = selected.loc[exposed, f"same_{mode}_peak_hours_{side}"].eq(
                        True
                    )
                    rate = float(same.mean() * 100) if len(same) else np.nan
                    bars[side].append(rate)
                    shift = (
                        selected.loc[exposed, f"nearest_{mode}_peak_shift_h_{side}"]
                        .abs()
                        .dropna()
                    )
                    stats.append(
                        {
                            "figure": "peak_timing",
                            "mode": mode,
                            "sampling": sampling,
                            "gap_hours": hours,
                            "hierarchy": side,
                            "exposed_responses": len(same),
                            "unexposed_responses": unexposed,
                            "zero_or_numerical_reference_peaks": numerical,
                            "exposed_site_years": site_years,
                            "exact_peak_hour_sets_preserved": int(same.sum()),
                            "preserved_percent": None if np.isnan(rate) else rate,
                            "nearest_absolute_peak_shift_h_median": float(
                                shift.median()
                            )
                            if len(shift)
                            else None,
                        }
                    )
            for offset, (side, _, color) in zip((-0.17, 0.17), SIDES):
                ax.bar(
                    np.arange(4) + offset,
                    bars[side],
                    width=0.31,
                    color=color,
                    alpha=0.85,
                )
            ax.set_xticks(range(4), ticks)
            ax.set_xlabel("Hours per block", fontsize=9)
            ax.set_xlim(-0.5, 3.5)
            ax.set_ylim(0, 105)
            ax.set_ylabel(
                f"{mode.capitalize()} peak-hour set\npreserved exactly (%)", fontsize=10
            )
            ax.set_title(label, fontsize=11)
    fig.legend(
        handles=[
            Line2D([0], [0], color=color, linewidth=7, label=label)
            for _, label, color in SIDES
        ],
        loc="upper center",
        bbox_to_anchor=(0.5, 0.94),
        ncol=2,
        frameon=False,
    )
    caption = "E: reference-peak responses actually hidden; U: positive reference peaks unexposed; Y: exposed site-years. E=0 means no exposure evidence; with E>0, a zero-height bar means 0% preserved.\nPreservation requires the exact set of all tied maximum-load hours; zero/numerical peaks ≤10⁻⁶ W/m² are excluded. Rates are descriptive scenario fractions, not confidence limits."
    caption += "\nSeasonal random: 4 blocks/file (4×hours); weather event: 1 block/file. Method comparisons are within each sampling stratum."
    finish(fig, "Peak timing among actually exposed peaks", caption, provisional)
    fig.subplots_adjust(
        top=0.85, bottom=0.24, left=0.08, right=0.99, hspace=0.6, wspace=0.3
    )
    return fig, stats


def plot(root, *, provisional=False):
    """Verify final analysis provenance and write four compact scientific figures."""
    root = Path(root)
    manifest_bytes = (root / "manifest.json").read_bytes()
    manifest = json.loads(manifest_bytes)
    if manifest["status"] != "complete" and not provisional:
        raise ValueError("Incomplete analysis requires explicit --provisional")
    partial = provisional or manifest["status"] != "complete"
    pairs = plot_inputs(root, manifest)
    folder = root / "figures"
    folder.mkdir(parents=True, exist_ok=True)
    plt.rcParams.update(
        {"font.family": "DejaVu Sans", "svg.fonttype": "none", "axes.axisbelow": True}
    )
    outputs, statistics = {}, []
    for quantity in ("annual", "peak"):
        fig, data = error_figure(pairs, quantity, partial)
        save(fig, folder, f"paired-{quantity}-errors", outputs)
        statistics.extend(data)
    for stem, function in (
        ("building-profile-changes", profile_figure),
        ("exposed-peak-timing", peak_timing_figure),
    ):
        fig, data = function(pairs, partial)
        save(fig, folder, stem, outputs)
        statistics.extend(data)
    data_path = folder / "figure-data.csv"
    pd.DataFrame(statistics).to_csv(data_path, index=False)
    outputs[data_path.name] = sha(data_path.read_bytes())
    receipt = {
        "status": "provisional" if partial else "complete",
        "created_utc": datetime.now(UTC).isoformat(),
        "plotter_sha256": sha(Path(__file__).read_bytes()),
        "analysis_manifest_sha256": sha(manifest_bytes),
        "input_table_sha256": {
            n: manifest["outputs"][n]
            for n in ("hierarchy-pairs.csv", "deduplicated-comparisons.csv")
        },
        "python": sys.version,
        "matplotlib": matplotlib.__version__,
        "numpy": np.__version__,
        "pandas": pd.__version__,
        "paired_responses": len(pairs),
        "site_years": len(pairs[["site_id", "year"]].drop_duplicates()),
        "outputs": outputs,
        "interpretation": "All plots use matched current/previous automatic physical masks; no donor-survivor ranking. Percentile tails and site-year spreads are empirical, not population confidence intervals. Percentage errors accompany absolute errors; exposed peak-hour ties use exact set equality.",
    }
    (folder / "manifest.json").write_text(
        json.dumps(receipt, indent=2, allow_nan=False) + "\n"
    )
    return receipt


def main():
    """Render verified analysis tables with explicit permission for provisional plots."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("analysis_root", type=Path)
    parser.add_argument("--provisional", action="store_true")
    args = parser.parse_args()
    receipt = plot(args.analysis_root, provisional=args.provisional)
    print(
        json.dumps(
            {k: receipt[k] for k in ("status", "paired_responses", "site_years")},
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
